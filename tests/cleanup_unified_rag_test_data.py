from __future__ import annotations

"""
MemorAi Unified RAG Stale Test Data Cleanup

Purpose
-------
Safely remove stale synthetic records created by earlier runs of:

    tests.test_unified_rag

This script ONLY targets synthetic records whose person/participant
name begins with:

    Unified Rahul

It does NOT delete:

    - normal registered people
    - real person encounters
    - real conversations
    - object memories
    - medicine memories
    - medicine events

Usage
-----

Preview only:

    python -m tests.cleanup_unified_rag_test_data

Actually delete:

    python -m tests.cleanup_unified_rag_test_data --delete
"""

import argparse
from typing import Any

from database.db_manager import (
    execute,
    fetch_all,
)

from database.conversation_vector_memory import (
    ConversationVectorMemory,
)


# ============================================================
# SAFETY CONFIGURATION
# ============================================================

TEST_PERSON_PREFIX = "Unified Rahul"

DELETE_FLAG = "--delete"


# ============================================================
# OUTPUT HELPERS
# ============================================================

def print_header(
    title: str,
) -> None:

    print()
    print("=" * 74)
    print(title)
    print("=" * 74)


def print_separator() -> None:

    print("-" * 74)


# ============================================================
# FIND STALE CONVERSATIONS
# ============================================================

def find_test_conversations(
) -> list[dict[str, Any]]:
    """
    Find only synthetic Unified RAG conversation records.

    We intentionally restrict the query to participant_text
    beginning with the known regression-test prefix.
    """

    pattern = (
        TEST_PERSON_PREFIX
        + "%"
    )

    return fetch_all(
        """
        SELECT
            id,
            title,
            participant_text,
            full_transcript,
            summary,
            status,
            started_at,
            ended_at,
            created_at
        FROM conversation_sessions
        WHERE participant_text LIKE %s
        ORDER BY id ASC
        """,
        (
            pattern,
        ),
    )


# ============================================================
# FIND STALE PEOPLE
# ============================================================

def find_test_people(
) -> list[dict[str, Any]]:
    """
    Find only synthetic people generated by the unified
    regression test.
    """

    pattern = (
        TEST_PERSON_PREFIX.lower()
        + "%"
    )

    return fetch_all(
        """
        SELECT
            id,
            name,
            display_name,
            relation,
            is_active,
            created_at
        FROM registered_people
        WHERE LOWER(name) LIKE %s
           OR LOWER(
                COALESCE(
                    display_name,
                    ''
                )
              ) LIKE %s
        ORDER BY id ASC
        """,
        (
            pattern,
            pattern,
        ),
    )


# ============================================================
# COUNT PERSON EVENTS
# ============================================================

def count_person_events(
    person_id: int,
) -> int:

    rows = fetch_all(
        """
        SELECT COUNT(*) AS total
        FROM person_events
        WHERE person_id = %s
        """,
        (
            int(person_id),
        ),
    )

    if not rows:
        return 0

    return int(
        rows[0].get(
            "total",
            0,
        )
        or 0
    )


# ============================================================
# COUNT FACE EMBEDDINGS
# ============================================================

def count_face_embeddings(
    person_id: int,
) -> int:

    rows = fetch_all(
        """
        SELECT COUNT(*) AS total
        FROM person_face_embeddings
        WHERE person_id = %s
        """,
        (
            int(person_id),
        ),
    )

    if not rows:
        return 0

    return int(
        rows[0].get(
            "total",
            0,
        )
        or 0
    )


# ============================================================
# PREVIEW CONVERSATIONS
# ============================================================

def preview_conversations(
    conversations: list[dict[str, Any]],
) -> None:

    print_header(
        "STALE UNIFIED RAG CONVERSATIONS"
    )

    if not conversations:

        print(
            "No stale Unified Rahul conversations found."
        )

        return

    print(
        f"Found {len(conversations)} "
        "synthetic conversation record(s)."
    )

    print()

    for conversation in conversations:

        conversation_id = (
            conversation.get(
                "id"
            )
        )

        participant = (
            conversation.get(
                "participant_text"
            )
            or ""
        )

        title = (
            conversation.get(
                "title"
            )
            or ""
        )

        started_at = (
            conversation.get(
                "started_at"
            )
        )

        transcript = str(
            conversation.get(
                "full_transcript"
            )
            or ""
        ).strip()

        print_separator()

        print(
            f"Conversation ID : {conversation_id}"
        )

        print(
            f"Participant     : {participant}"
        )

        print(
            f"Title           : {title}"
        )

        print(
            f"Started At      : {started_at}"
        )

        if transcript:

            preview = transcript

            if len(preview) > 160:

                preview = (
                    preview[:157]
                    + "..."
                )

            print(
                f"Transcript      : {preview}"
            )


# ============================================================
# PREVIEW PEOPLE
# ============================================================

def preview_people(
    people: list[dict[str, Any]],
) -> None:

    print_header(
        "STALE UNIFIED RAG PEOPLE"
    )

    if not people:

        print(
            "No stale Unified Rahul people found."
        )

        return

    print(
        f"Found {len(people)} "
        "synthetic person record(s)."
    )

    print()

    for person in people:

        person_id = int(
            person["id"]
        )

        event_count = (
            count_person_events(
                person_id
            )
        )

        embedding_count = (
            count_face_embeddings(
                person_id
            )
        )

        print_separator()

        print(
            f"Person ID       : {person_id}"
        )

        print(
            "Name            : "
            f"{person.get('name')}"
        )

        print(
            "Display Name    : "
            f"{person.get('display_name')}"
        )

        print(
            "Relation        : "
            f"{person.get('relation')}"
        )

        print(
            "Person Events   : "
            f"{event_count}"
        )

        print(
            "Face Embeddings : "
            f"{embedding_count}"
        )


# ============================================================
# DELETE CONVERSATION VECTOR
# ============================================================

def delete_conversation_vector(
    vector_memory: ConversationVectorMemory,
    conversation_id: int,
) -> None:

    memory = (
        vector_memory.get_conversation(
            conversation_id
        )
    )

    if memory is None:

        print(
            "  Vector memory: "
            "already absent"
        )

        return

    vector_memory.delete_conversation(
        conversation_id
    )

    print(
        "  Vector memory: deleted"
    )


# ============================================================
# DELETE MYSQL CONVERSATION
# ============================================================

def delete_mysql_conversation(
    conversation_id: int,
) -> None:

    # conversation_segments are deleted automatically
    # because their foreign key uses ON DELETE CASCADE.

    execute(
        """
        DELETE FROM conversation_sessions
        WHERE id = %s
        """,
        (
            int(conversation_id),
        ),
    )

    print(
        "  MySQL conversation: deleted"
    )


# ============================================================
# DELETE PERSON
# ============================================================

def delete_test_person(
    person_id: int,
) -> None:
    """
    Delete one synthetic person safely.

    Important:

    person_events uses ON DELETE RESTRICT, therefore events
    must be deleted first.

    person_face_embeddings uses ON DELETE CASCADE, but we
    delete them explicitly so cleanup output and behavior
    remain obvious.
    """

    # --------------------------------------------------------
    # PERSON EVENTS
    # --------------------------------------------------------

    execute(
        """
        DELETE FROM person_events
        WHERE person_id = %s
        """,
        (
            int(person_id),
        ),
    )

    print(
        "  Person events: deleted"
    )

    # --------------------------------------------------------
    # FACE EMBEDDINGS
    # --------------------------------------------------------

    execute(
        """
        DELETE FROM person_face_embeddings
        WHERE person_id = %s
        """,
        (
            int(person_id),
        ),
    )

    print(
        "  Face embeddings: deleted"
    )

    # --------------------------------------------------------
    # REGISTERED PERSON
    # --------------------------------------------------------

    execute(
        """
        DELETE FROM registered_people
        WHERE id = %s
        """,
        (
            int(person_id),
        ),
    )

    print(
        "  Registered person: deleted"
    )


# ============================================================
# DELETE CONVERSATIONS
# ============================================================

def cleanup_conversations(
    conversations: list[dict[str, Any]],
) -> None:

    if not conversations:

        return

    print_header(
        "DELETING STALE CONVERSATIONS"
    )

    vector_memory = (
        ConversationVectorMemory()
    )

    for conversation in conversations:

        conversation_id = int(
            conversation["id"]
        )

        participant = str(
            conversation.get(
                "participant_text"
            )
            or ""
        )

        # ----------------------------------------------------
        # SECOND SAFETY CHECK
        # ----------------------------------------------------

        if not participant.lower().startswith(
            TEST_PERSON_PREFIX.lower()
        ):

            raise RuntimeError(
                (
                    "Safety check failed. Refusing "
                    "to delete conversation "
                    f"{conversation_id}."
                )
            )

        print_separator()

        print(
            "Deleting conversation "
            f"{conversation_id}"
        )

        print(
            f"Participant: {participant}"
        )

        # Chroma first.
        #
        # This avoids leaving a vector pointing to a deleted
        # MySQL conversation if vector deletion fails.

        delete_conversation_vector(
            vector_memory=(
                vector_memory
            ),
            conversation_id=(
                conversation_id
            ),
        )

        delete_mysql_conversation(
            conversation_id
        )


# ============================================================
# DELETE PEOPLE
# ============================================================

def cleanup_people(
    people: list[dict[str, Any]],
) -> None:

    if not people:

        return

    print_header(
        "DELETING STALE PEOPLE"
    )

    for person in people:

        person_id = int(
            person["id"]
        )

        name = str(
            person.get(
                "name"
            )
            or ""
        )

        display_name = str(
            person.get(
                "display_name"
            )
            or ""
        )

        # ----------------------------------------------------
        # SECOND SAFETY CHECK
        # ----------------------------------------------------

        valid_name = (
            name.lower().startswith(
                TEST_PERSON_PREFIX.lower()
            )
        )

        valid_display_name = (
            display_name.lower().startswith(
                TEST_PERSON_PREFIX.lower()
            )
        )

        if not (
            valid_name
            or valid_display_name
        ):

            raise RuntimeError(
                (
                    "Safety check failed. Refusing "
                    "to delete person "
                    f"{person_id}."
                )
            )

        print_separator()

        print(
            f"Deleting person {person_id}"
        )

        print(
            f"Display name: {display_name}"
        )

        delete_test_person(
            person_id
        )


# ============================================================
# VERIFY CLEANUP
# ============================================================

def verify_cleanup(
) -> bool:

    remaining_conversations = (
        find_test_conversations()
    )

    remaining_people = (
        find_test_people()
    )

    print_header(
        "CLEANUP VERIFICATION"
    )

    print(
        "Remaining Unified Rahul conversations: "
        f"{len(remaining_conversations)}"
    )

    print(
        "Remaining Unified Rahul people: "
        f"{len(remaining_people)}"
    )

    if (
        remaining_conversations
        or remaining_people
    ):

        print()
        print(
            "WARNING: Some synthetic regression "
            "records still remain."
        )

        return False

    print()
    print(
        "PASS: No stale Unified Rahul MySQL "
        "records remain."
    )

    return True


# ============================================================
# ARGUMENTS
# ============================================================

def parse_arguments(
) -> argparse.Namespace:

    parser = argparse.ArgumentParser(
        description=(
            "Preview or remove stale MemorAi "
            "Unified RAG regression-test data."
        )
    )

    parser.add_argument(
        DELETE_FLAG,
        action="store_true",
        dest="delete",
        help=(
            "Actually delete matching synthetic "
            "test records. Without this flag the "
            "script is preview-only."
        ),
    )

    return parser.parse_args()


# ============================================================
# MAIN
# ============================================================

def main(
) -> None:

    args = parse_arguments()

    print_header(
        "MemorAi Unified RAG Test Data Cleanup"
    )

    print(
        "Safety prefix:"
    )

    print(
        f"  {TEST_PERSON_PREFIX}"
    )

    print()

    print(
        "This script targets ONLY synthetic "
        "Unified RAG test data."
    )

    # --------------------------------------------------------
    # DISCOVERY
    # --------------------------------------------------------

    conversations = (
        find_test_conversations()
    )

    people = (
        find_test_people()
    )

    preview_conversations(
        conversations
    )

    preview_people(
        people
    )

    # --------------------------------------------------------
    # NOTHING FOUND
    # --------------------------------------------------------

    if (
        not conversations
        and not people
    ):

        print_header(
            "RESULT"
        )

        print(
            "Nothing to clean."
        )

        return

    # --------------------------------------------------------
    # PREVIEW MODE
    # --------------------------------------------------------

    if not args.delete:

        print_header(
            "PREVIEW ONLY"
        )

        print(
            "No records were deleted."
        )

        print()
        print(
            "Review the records above carefully."
        )

        print()
        print(
            "If every listed record is synthetic "
            "Unified RAG test data, run:"
        )

        print()
        print(
            "python -m "
            "tests.cleanup_unified_rag_test_data "
            "--delete"
        )

        return

    # --------------------------------------------------------
    # DELETE MODE
    # --------------------------------------------------------

    print_header(
        "DELETE MODE"
    )

    print(
        "Deleting only records matching the "
        "synthetic Unified Rahul prefix."
    )

    cleanup_conversations(
        conversations
    )

    cleanup_people(
        people
    )

    success = verify_cleanup()

    print_header(
        "FINAL RESULT"
    )

    if success:

        print(
            "PASS: Stale Unified RAG regression "
            "data cleaned successfully."
        )

    else:

        raise RuntimeError(
            (
                "Cleanup finished, but some "
                "synthetic records remain."
            )
        )


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":

    main()